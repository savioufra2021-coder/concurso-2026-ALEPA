export function isGeralDisciplineId(id: string): boolean {
  return id.startsWith('geral_');
}

export function isGeralMaterial(mat: Pick<StudyMaterial, 'disciplineId' | 'libraryCategoryId'>): boolean {
  return isGeralDisciplineId(mat.disciplineId) || Boolean(mat.libraryCategoryId?.startsWith('geral_cat_'));
}

